/* ----- primitives ----- */
const B = ({ p, s, m, r }: { p: V3; s: V3; m: THREE.Material; r?: V3 }) => (
  <mesh position={p} rotation={r} material={m}><boxGeometry args={s} /></mesh>
);
/** cylinder along Z (forward) */
const Cz = ({ p, r, r2, l, m, seg = 14 }: { p: V3; r: number; r2?: number; l: number; m: THREE.Material; seg?: number }) => (
  <mesh position={p} rotation={[Math.PI / 2, 0, 0]} material={m}><cylinderGeometry args={[r, r2 ?? r, l, seg]} /></mesh>
);
/** cylinder along X (sideways) */
const Cx = ({ p, r, l, m, seg = 12 }: { p: V3; r: number; l: number; m: THREE.Material; seg?: number }) => (
  <mesh position={p} rotation={[0, 0, Math.PI / 2]} material={m}><cylinderGeometry args={[r, r, l, seg]} /></mesh>
);
/** cylinder along Y (vertical) */
const Cy = ({ p, r, l, m, seg = 12 }: { p: V3; r: number; l: number; m: THREE.Material; seg?: number }) => (
  <mesh position={p} material={m}><cylinderGeometry args={[r, r, l, seg]} /></mesh>
);
/** cone pointing forward (-Z) or backward */
const Cone = ({ p, r, l, m, back = false, seg = 12 }: { p: V3; r: number; l: number; m: THREE.Material; back?: boolean; seg?: number }) => (
  <mesh position={p} rotation={[back ? Math.PI / 2 : -Math.PI / 2, 0, 0]} material={m}><coneGeometry args={[r, l, seg]} /></mesh>
);
/** ring around the Z axis */
const Ring = ({ p, r, t, m }: { p: V3; r: number; t: number; m: THREE.Material }) => (
  <mesh position={p} material={m}><torusGeometry args={[r, t, 8, 28]} /></mesh>
);
const Bore = ({ p, r }: { p: V3; r: number }) => <Cz p={p} r={r} l={0.012} m={M.black} />;

